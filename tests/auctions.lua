local H = ...
local function fixture()
	local w, FK = H.new()
	FK.Database = { Fish = { [1] = { name = "A" }, [2] = { name = "B" }, [3] = { name = "C" } } }
	w:load("modules/AuctionHouse.lua")
	function w:result(name, buyout, count)
		self.listings = name and { { name = name, buyout = buyout or 20, count = count or 1 } } or {}
		self:event("AUCTION_ITEM_LIST_UPDATE")
	end
	return w, FK, FK.AuctionHouse
end

H.test("completed query timeout cannot skip the next fish", function()
	local w, FK, ah = fixture()
	ah:StartScan()
	w:advance(1)
	w:result("A", 60, 3)
	H.eq(w.queries[2].name, "B")
	H.eq(FK.db.ahPrices[1], 20, "unit buyout")
	w:advance(2)
	H.eq(#w.queries, 2, "B still has one second to respond")
	w:advance(0.5)
	w:result("B")
	H.eq(w.queries[3].name, "C")
	w:advance(0.5)
	H.eq(FK.db.ahPriceTimes[3], nil, "B timeout cannot complete C")
	w:result("C")
	H.eq(FK.db.ahPrices[3], 20)
end)

H.test("late auction results keep the current query pending", function()
	local w, FK, ah = fixture()
	ah:StartScan()
	w:advance(3)
	H.eq(w.queries[2].name, "B")
	w:result("A")
	H.eq(#w.queries, 2, "late A results cannot finish B")
	H.eq(FK.db.ahPriceTimes[2], nil, "B must remain eligible for a later scan")
	w:advance(1)
	w:result("B", 60, 3)
	H.eq(FK.db.ahPrices[2], 20)
	H.eq(w.queries[3].name, "C")
end)

H.test("mismatched results do not cancel the current timeout", function()
	local w, FK, ah = fixture()
	ah:StartScan()
	w:result("B")
	w:advance(3)
	H.eq(w.queries[2].name, "B")
	H.eq(FK.db.ahPriceTimes[1], nil)
end)

H.test("matching bid-only listings complete without a buyout", function()
	local w, FK, ah = fixture()
	ah:StartScan()
	w:result("A", 0)
	H.eq(FK.db.ahPrices[1], nil)
	H.eq(FK.db.ahPriceTimes[1], w.env.time())
	H.eq(w.queries[2].name, "B")
end)

H.test("empty results after a timeout cannot mark another fish fresh", function()
	local w, FK, ah = fixture()
	ah:StartScan()
	w:advance(3)
	w:result(nil)
	H.eq(#w.queries, 2, "an empty response could still belong to A")
	H.eq(FK.db.ahPriceTimes[2], nil)
	w:result("B")
	H.eq(FK.db.ahPrices[2], 20)
	w:result(nil)
	H.eq(FK.db.ahPriceTimes[3], nil, "a later empty response is still ambiguous")
	w:advance(3)
	H.eq(#w.queries, 3, "the normal timeout still finishes the scan")
	w:event("AUCTION_HOUSE_CLOSED")
	ah:StartScan()
	w:result(nil)
	H.eq(FK.db.ahPriceTimes[1], w.env.time(), "a new auction visit accepts ordinary empty results")
end)

H.test("old timeout cannot advance a restarted scan", function()
	local w, _, ah = fixture()
	ah:StartScan()
	w:advance(1)
	w:event("AUCTION_HOUSE_CLOSED")
	ah:StartScan()
	H.eq(w.queries[2].name, "A")
	w:advance(2)
	H.eq(#w.queries, 2)
	w:advance(1)
	H.eq(w.queries[3].name, "B", "new scan's own timeout")
end)

H.test("aborted throttle ticker cannot send in a new scan", function()
	local w, _, ah = fixture()
	w.canQuery = false
	ah:StartScan()
	local oldTicker = w.timers[#w.timers]
	w:event("AUCTION_HOUSE_CLOSED")
	ah:StartScan()
	w.canQuery = true
	-- A callback already queued for dispatch must be harmless even after Cancel.
	oldTicker.callback()
	H.eq(#w.queries, 0)
	w:advance(0.2)
	H.eq(#w.queries, 1)
	H.eq(w.queries[1].name, "A")
end)

H.test("query keeps its full timeout after throttling", function()
	local w, _, ah = fixture()
	w.canQuery = false
	ah:StartScan()
	w:advance(1)
	H.eq(#w.queries, 0)
	w.canQuery = true
	w:advance(0.21)
	H.eq(#w.queries, 1)
	w:advance(w.queries[1].time + 2.9 - w.now)
	H.eq(#w.queries, 1)
	w:advance(0.11)
	H.eq(w.queries[2].name, "B")
end)

H.test("empty results and fresh prices finish normally", function()
	local w, FK, ah = fixture()
	FK.db.ahPriceTimes[1] = w.env.time()
	ah:StartScan()
	H.eq(w.queries[1].name, "B")
	w:result(nil)
	H.eq(FK.db.ahPriceTimes[2], w.env.time())
	w:result("C")
	w:advance(4)
	H.eq(#w.queries, 2)
	ah:StartScan()
	H.eq(#w.queries, 2, "fresh items are skipped")
end)

H.test("closing auction house ends a throttle wait", function()
	local w, _, ah = fixture()
	w.canQuery = false
	ah:StartScan()
	w.env.AuctionFrame:Hide()
	w:advance(0.2)
	w.canQuery = true
	w:advance(4)
	H.eq(#w.queries, 0)
end)
